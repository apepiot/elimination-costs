function [R, F, V] = R_V2(Y,pi,beta1, beta2,e1,e2,gamma1,gamma2,mu)
%UNTITLED Summary of this function goes here
%   Detailed explanation goes here

    Y0=Y(1);Y1=Y(2);Y2=Y(3);Y3=Y(4);Y4=Y(5);Y5=Y(6);

    F1 = [beta1*Y0,0,e1*Y0,0;...
        0,0,0,0;...
        beta1*Y2, beta1*Y1 + e1*Y3, e1*Y2,0;...
        0,0,0,0];
    F2 = [0,0,0,0;...
        0,beta2*Y0,e2*Y0,beta2*Y0;...
        beta2*Y2 + e2*Y3 + beta2*Y4, beta2*Y1, e2*Y1, beta2*Y1;...
        0, beta2*Y5, e2*Y5, beta2*Y5];
    
    V = [beta2*Y2 + e2*Y3 + beta2*Y4 + mu + gamma1, beta2*Y1, gamma2 - e2*Y1, beta2*Y1;...
        beta1*Y2, beta1*Y1 + e1*Y3 + mu + gamma2, e1*Y2, 0;...
        0 , 0, gamma2+gamma1+mu, 0;...
        0,0, -gamma1, mu + gamma2];
    
    F = F1+F2;
    matrice = F*V^(-1);
    R = eig(matrice);
    
end

