function [U12,P12,dU12] = U12_SIS2(rho,beta1,beta2,gamma1,gamma2,s1,s2,b,mu,c)
    % Utility function of testing for the SISxSIS model , s1 diff of s2 and
    % I12-> S    
    gamma1p = gamma1 + s1*rho;
    gamma2p = gamma2 + s2*rho;
    R1p  = beta1./(gamma1p+mu);
    R2p  = beta2./(gamma2p+mu);

    s12 = (gamma2p./R1p + gamma1p./R2p + mu + (s1.*s2.*rho).*(1-1./R1p-1./R2p))./(beta1+beta2-mu-s1.*s2.*rho);
    P12 = 1-s12;

    %utility
    U12 = rho.*(P12-c);
    
    dU12 = 1 - rho.*(((s2.*(gamma1 + mu + rho.*s1))./beta1 +...
        (s1.*(gamma2 + mu + rho*s2))./beta2 + (s1*(gamma2 + rho*s2))./beta1 + ...
        (s2*(gamma1 + rho*s1))/beta2 - s1*s2*((gamma1 + mu + rho*s1)/beta1 +...
        (gamma2 + mu + rho*s2)/beta2 - 1) - rho*s1*s2*(s1/beta1 + s2/beta2))./...
        (beta1 + beta2 - mu - rho.*s1*s2) + (s1*s2*(mu + ((gamma2 + rho*s2).*...
        (gamma1 + mu + rho*s1))/beta1 + ((gamma1 + rho*s1).*(gamma2 + mu +...
        rho.*s2))/beta2 - rho.*s1*s2.*((gamma1 + mu + rho.*s1)./beta1 +...
        (gamma2 + mu + rho*s2)/beta2 - 1)))./(beta1 + beta2 - mu - rho.*s1*s2).^2) - ...
        (mu + ((gamma2 + rho*s2).*(gamma1 + mu + rho*s1))./beta1 + ...
        ((gamma1 + rho*s1).*(gamma2 + mu + rho*s2))./beta2 - rho.*s1*s2.*...
        ((gamma1 + mu + rho*s1)./beta1 + (gamma2 + mu + rho*s2)./beta2 - 1))./...
        (beta1 + beta2 - mu - rho*s1*s2) - c;
end

